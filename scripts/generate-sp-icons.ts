/**
 * Writes src/kits/sharepoint/icons.generated.ts: the Fluent System Icons (MIT, © Microsoft) the
 * SharePoint kit uses, as 20px "regular" SVG paths. Only a curated list is bundled, so the app
 * stays small and works offline. Fails if a name is not in the installed `@fluentui/svg-icons`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const dir = resolve(dirname(require.resolve('@fluentui/svg-icons/package.json')), 'icons');

